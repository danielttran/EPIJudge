def add(
    slug,
    method,
    params,
    result,
    description,
    approach,
    complexity,
    space,
    examples,
    *,
    mode="pure",
    cls="Solution",
    conventions="",
    correctness="",
    edges="",
    difficulty="Medium",
):
    meta = next(
        x
        for x in json.loads(
            (ROOT / "interviewcake/provenance/source_metadata.json").read_text(
                encoding="utf-8"
            )
        )
        if x["sourceId"] == slug
    )
    S.append(
        {
            "id": meta["id"],
            "sourceId": slug,
            "title": meta["title"],
            "sourceUrl": meta["url"],
            "position": meta["position"],
            "topic": meta["url"].split("section=")[-1],
            "difficulty": difficulty,
            "method": method,
            "params": [{"name": n, "type": t} for n, t in params],
            "result": result,
            "mode": mode,
            "className": cls,
            "description": description,
            "approach": approach,
            "timeComplexity": complexity,
            "spaceComplexity": space,
            "examplesData": examples,
            "bankConventions": conventions,
            "correctness": correctness,
            "edgeCases": edges,
        }
    )


